    fun norm(w: String): String = w.replace(Regex("[\\u0591-\\u05C7]"), "").replace("ײ", "יי").replace("װ", "וו").replace("ױ", "וי").replace("ײַ", "יי")
        .trim('.', ',', ':', ';', '!', '?', '"', '\'', '(', ')', '[', ']', '–', '-', '״', '׳')

    /** Meaning of a word, trying the common Yiddish endings and the past-tense ge- prefix. */
    fun gloss(raw: String): String? {
        val w = norm(raw)
        if (w.length < 1) return null
        G[w]?.let { return it }
        val tries = ArrayList<String>()
        for (suf in listOf("ן", "ען", "ט", "טע", "טן", "ע", "ער", "ס", "עס", "דיק", "דיקע", "ונג", "ונגען", "ט'ן", "ס'")) if (w.length > suf.length + 2 && w.endsWith(suf)) tries.add(w.removeSuffix(suf))
        if (w.startsWith("גע") && w.length > 4) { val x = w.removePrefix("גע"); tries.add(x); tries.add(x.removeSuffix("ט")); tries.add(x.removeSuffix("ן")) }
        if (w.startsWith("צו") && w.length > 4) tries.add(w.removePrefix("צו"))
        for (t in tries) { G[t]?.let { return it }; G[t + "ן"]?.let { return it }; G[t + "ט"]?.let { return it } }
        return null
    }

    /** Does the text look like Yiddish (many of its common little words)? */
    fun looksYiddish(text: String): Boolean {
        val ws = text.split(Regex("\\s+")).map(::norm)
        val marks = setOf("און", "איז", "דער", "דאס", "ניט", "נישט", "פון", "מיט", "אויף", "וואס", "אז", "זיך", "דעם", "ווי")
        return ws.count { it in marks } >= maxOf(3, ws.size / 25)
    }
}

class YiddishActivity : BaseActivity() {
