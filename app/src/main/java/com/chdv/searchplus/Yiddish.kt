        }
        head.addView(label("🗣 לימוד יידיש", 21f, Color.WHITE, true))
        head.addView(label("פארשטייט יעדעס ווארט – מבינים כל מילה. מדביקים טקסט ביידיש, או פותחים מתוך עמוד בקורא (⋯ › פירוש יידיש), ומתחת לכל מילה מופיע הפירוש בעברית.", 14f, 0xEEFFFFFF.toInt()).apply { setPadding(0, dp(6), 0, 0) })
        box.addView(head, lp(MATCH, WRAP).m(0, dp(4), 0, dp(12)))
        input = EditText(this).apply {
            hint = "הדביקו או כתבו כאן טקסט ביידיש…"
            minLines = 3; gravity = Gravity.TOP or Gravity.START
            textDirection = View.TEXT_DIRECTION_RTL
            background = roundBg(Col.CARD, dp(14).toFloat(), dp(1), Col.LINE)
            setPadding(dp(12), dp(10), dp(12), dp(10))
        }
        box.addView(input, lp(MATCH, WRAP))
        box.addView(pill("פירוש המילים") { render(input.text.toString()) }, lp(MATCH, WRAP).m(0, dp(8), 0, dp(8)))
        stat = label("", 13.5f, Col.SUB)
        box.addView(stat)
        out = vbox()
        box.addView(out, lp(MATCH, WRAP))
        screen("🗣 לימוד יידיש", ScrollView(this).apply { addView(box) })
        intent.getStringExtra("text")?.let { input.setText(it); render(it) }
    }

    private fun render(text: String) {
        out.removeAllViews()
        val words = text.split(Regex("\\s+")).filter { it.isNotBlank() }.take(1500)
        val flow = FlowLayout(this).apply { gap = dp(4) }
        var known = 0
        for (w in words) {
            val g = Yiddish.gloss(w)
            if (g != null) known++
            flow.addView(vbox().apply {
                gravity = Gravity.CENTER_HORIZONTAL
                setPadding(dp(5), dp(3), dp(5), dp(3))
                if (g != null) background = roundBg(Col.ACC_LIGHT, dp(8).toFloat())
                addView(label(w, 17f, Col.TEXT, g != null).apply { gravity = Gravity.CENTER; textAlignment = View.TEXT_ALIGNMENT_CENTER })
                addView(label(g ?: " ", 11.5f, Col.ACC).apply { gravity = Gravity.CENTER; textAlignment = View.TEXT_ALIGNMENT_CENTER })
            })
        }
        out.addView(flow, lp(MATCH, WRAP))
        stat.text = if (words.isEmpty()) "" else "פורשו $known מתוך ${words.size} מילים · מילים ממקור עברי (ענין, פשט…) נשארות כמו שהן"
    }
}
